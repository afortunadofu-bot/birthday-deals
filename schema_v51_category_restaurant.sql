-- v51：類別「連鎖餐廳」改名「餐廳」
-- ---------------------------------------------------------------------
-- celine 回饋：「19to1鮮選牛排專賣店」這種單店牛排館，不屬於速食／火鍋燒肉，
-- 卻也不太敢選「連鎖餐廳」（沒有很多分店，感覺不算「連鎖」），結果只能選
-- 「其他」——但「其他」在依類別篩選時常被當成非餐飲類直接漏掉，這筆優惠
-- 等於變相從飲食類篩選結果裡消失。
--
-- 原本「連鎖餐廳」底下其實已經混了王品牛排、小時厚牛排這種不見得每個人
-- 都認得是「連鎖」的品牌，把類別名稱拿掉「連鎖」兩字改成「餐廳」，泛指
-- 各種內用型餐廳（含單店），跟「速食」「火鍋燒肉」的界線更清楚，也不會
-- 逼單店老闆為了避嫌選到「其他」去。
--
-- category 欄位是純文字（沒有 check constraint 限制固定選項），前端
-- CATEGORIES 陣列改名以後，既有資料庫裡舊的 category='連鎖餐廳' 這一批
-- 要一起改成'餐廳'，不然這些既有優惠的類別篩選會對不起來（變成篩不到）。
-- 可重複執行，跑第二次不會壞（第二次執行時已經沒有'連鎖餐廳'可改，等於
-- 沒動作）。
-- ---------------------------------------------------------------------
update public.offers set category='餐廳' where category='連鎖餐廳';
