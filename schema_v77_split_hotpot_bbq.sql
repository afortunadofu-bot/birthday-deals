-- ---------------------------------------------------------------------
-- 真的分
-- ---------------------------------------------------------------------
update public.offers
   set category = case
     when (coalesce(brand,'') || ' ' || coalesce(offer,''))
          ~* '燒肉|焼肉|烤肉|燒烤|乾杯|KANPAI|燒丼' then '燒肉'
     else '火鍋'
   end
 where category = '火鍋燒肉';

