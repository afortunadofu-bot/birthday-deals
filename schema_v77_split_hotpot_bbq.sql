--
--   celine：「提議新增分類標籤：燒肉 飲料 甜點 火鍋」。
--   飲料、甜點烘焙本來就是獨立類別（甜點烘焙連麵包店一起收，所以沒改名），
--   真正混在一起的是「火鍋燒肉」——站上 73 筆裡 50 筆是鍋物、22 筆是燒肉，
--   想「今天只想吃燒肉」或「只想吃鍋」的人，篩選完還是得自己一筆一筆看。
--
--   category 是純文字欄位（沒有 check constraint，見 schema.sql），所以不用改
--   結構，只要把既有的 73 筆分到新的兩個值。分法是看店名跟優惠內容的關鍵字：
--
--     1. 店名或優惠內容出現 燒肉／焼肉／烤肉／燒烤／乾杯／KANPAI／燒丼 → 燒肉
--     2. 其餘一律 → 火鍋
--
--   之所以敢讓「其餘」一律當火鍋：這一格裡剩下的不是「鍋／涮／麻辣」就是
--   壽喜燒、打邊爐、串串香這種名字裡沒有「鍋」字的鍋物；逐筆看過 73 筆，
--   兩邊都沒命中的只有「泰滾 Rolling Thai」一家，而它本來就是泰式火鍋。
--   （「石頭燒肉」先命中燒肉，不會因為有「石頭」兩個字被當成石頭火鍋。）
--
--   跑之前先用下面那段 select 看一遍分類結果，覺得哪一筆不對，跑完直接在
--   後台編輯那一筆改掉就好（不用改這支 SQL）。
--
--   可重複執行：只動 category='火鍋燒肉' 的列，跑第二次就沒有東西可動了。
-- =====================================================================

