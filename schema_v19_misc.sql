-- ---------------------------------------------------------------------
-- 1) 管理員審核前直接編輯投稿內容時，把改了哪些欄位記下來，
--    投稿人自己在「我的投稿」點細節就看得到「被改了哪」。
-- ---------------------------------------------------------------------
alter table public.offers add column if not exists admin_edit_diff jsonb;

-- ---------------------------------------------------------------------
-- 2) 需同行者篩選（例如買一送一，一個人去用不了）。
-- ---------------------------------------------------------------------
alter table public.offers add column if not exists requires_companion boolean not null default false;

-- 用關鍵字先幫現有資料標記一版，之後管理員／投稿人可以自己在編輯裡修正。
update public.offers set requires_companion = true
where requires_companion = false
  and (offer ~ '買.?[一1].?送.?[一1]|買[一1]送[一1]|兩人|2人|雙人|同行|偕同|一人一份|每.?人.?限|限用餐.?人'
       or conditions ~ '兩人|雙人|同行|偕同|每.?人.?限');

