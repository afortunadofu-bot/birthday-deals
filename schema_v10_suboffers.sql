-- 卡片標題還是維持集團合併寫法（不拆成 17 張卡片洗版面），但卡片上會多一個
-- 「查看各品牌優惠」的展開按鈕，把每個子品牌實際的優惠內容分開列出來，不再
-- 只有一句籠統的摘要。
--
-- 用法：整份貼到 SQL Editor 執行一次即可（可重複執行）。
-- =====================================================================

