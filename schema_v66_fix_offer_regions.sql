-- v66：修正兩筆優惠的適用地區（選擇性，建議跑）
--
--   抓分店時發現這兩筆的「適用地區」跟品牌實際有的分店對不起來，
--   結果是照現在的地區去 Google 查，永遠查不到任何分店：
--
--   1. 喬義思 Choice：優惠寫「台北市」，但「喬義思窯烤手作廚房」在 Google 上
--      只有基隆店、嘉義莊園店、苗栗頭份尚順店，台北沒有店。
--   2. 烤狀猿日式燒肉：優惠寫「宜蘭縣」，但「烤狀猿」在 Google 上只有台中大里店、
--      台中南屯（新文心）店、彰化員林店。
--
--   改成實際有分店的縣市，「附近」功能才找得到，地區篩選也才不會誤導
--   （台北的使用者點進去卻發現最近的店在基隆）。
--
--   ⚠️ 如果你確認過優惠本來就只限某個縣市（例如快閃店、已經收掉的分店），
--      那就不要跑這一支，改成把優惠本身停用或修正。
--
--   可重複執行。
-- =====================================================================

update public.offers
   set regions = array['基隆市','嘉義市','苗栗縣']
 where brand = '喬義思 Choice'
   and regions is distinct from array['基隆市','嘉義市','苗栗縣'];

update public.offers
   set regions = array['台中市','彰化縣']
 where brand = '烤狀猿日式燒肉'
   and regions is distinct from array['台中市','彰化縣'];

