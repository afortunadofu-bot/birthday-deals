-- v80：問題回報多一種類型「重複的優惠」
--
--   嵐：「多一個發現重複可以回報的按鈕」。
--
--   同一家店被投稿兩次很常見（「再睡5分鐘」跟「再睡五分鐘」就是真的兩張），
--   以前只能叫人自己去「問題回報」打一段「我覺得這兩筆一樣」。現在優惠詳情
--   裡有一顆「🔁 這筆重複了」，按下去會開回報視窗、先把 `#編號 店名` 填好，
--   使用者只要補「跟哪一筆重複」。
--
--   這些回報要能跟一般的 bug 分開看（後台處理方式完全不同：重複是去合併面板
--   併兩張，不是修程式），所以 type 多一個值。
--
--   沒跑這一支的話，前端送出時會被 check constraint 擋下來，會自動退回
--   type='bug' 並在內文前面加 [重複]——使用者不會白填一次，但後台就沒辦法
--   單獨篩出來。
--
--   可重複執行。
-- =====================================================================

alter table public.site_feedback drop constraint if exists site_feedback_type_check;
alter table public.site_feedback
  add constraint site_feedback_type_check
  check (type in ('bug','suggestion','duplicate'));
