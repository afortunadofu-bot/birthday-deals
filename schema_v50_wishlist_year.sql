-- v50：待辦清單加「年度」標籤，可以提早存明年的代辦
-- ---------------------------------------------------------------------
-- 嵐的回饋：想要提早存明年的代辦，不用等到真的到了明年才能加。待辦清單
-- 加一個 year 欄位，預設是「加進去的當下那一年」——收藏按鈕（星號圖示）
-- 維持原本一鍵收藏的簡單操作，不用每次點收藏都先問一次年度；真的要規劃
-- 明年的話，到「待辦清單」面板裡把該筆項目「移到明年」即可（前端另外
-- 呼叫 update 改這個欄位，不需要新的 RPC）。
--
-- default extract(year from now())::int 是每一筆「新增當下」各自算，不是
-- migration 執行當下算一次就固定死──既有資料跑這支的時候會被這行 default
-- 補上「現在」的年份（也就是今年），符合「這些本來就是今年收藏的」的事實。
-- ---------------------------------------------------------------------
alter table public.wishlist
  add column if not exists year int not null default extract(year from now())::int;
